"""Real, executable tests for nothierly_genesis/causal_impact_engine.py.

Real DoWhy computation throughout (never mocked -- faking the causal
inference would defeat the point). The central test validates DoWhy's
real estimate against *known* ground truth from synthetic data
generated by this module's own structural equations -- the real,
standard way a causal-inference pipeline is unit-tested, since the
true causal effect is never directly observable in real market data.
"""

from __future__ import annotations

import math

import pytest

from nothierly_genesis.causal_impact_engine import (
    MarketImpactAction,
    estimate_causal_effect,
    generate_synthetic_market_data,
    load_real_market_features,
    parse_action,
)

# =============================================================================
# parse_action
# =============================================================================


def test_parses_buy_action() -> None:
    action = parse_action("do(Buy_100_BTC)")
    assert action == MarketImpactAction(side="Buy", quantity=100.0, asset="BTC")


def test_parses_sell_action_with_decimal_quantity() -> None:
    action = parse_action("do(Sell_50.5_ETH)")
    assert action.side == "Sell"
    assert action.quantity == 50.5
    assert action.asset == "ETH"


def test_rejects_malformed_action() -> None:
    with pytest.raises(ValueError, match="grammar"):
        parse_action("Buy 100 BTC")


def test_rejects_unknown_side() -> None:
    with pytest.raises(ValueError, match="grammar"):
        parse_action("do(Hold_100_BTC)")


def test_rejects_negative_quantity() -> None:
    with pytest.raises(ValueError, match="grammar"):
        parse_action("do(Buy_-5_BTC)")


# =============================================================================
# generate_synthetic_market_data
# =============================================================================


def test_synthetic_data_has_required_columns() -> None:
    df, _ = generate_synthetic_market_data(n_samples=100)
    assert set(df.columns) == {"Volume", "Spread", "Adverse_Selection", "Price_Slippage"}


def test_synthetic_data_true_effect_matches_the_real_structural_formula() -> None:
    _, true_effect = generate_synthetic_market_data(
        volume_to_spread=0.5, spread_to_adverse=0.8, adverse_to_slippage=1.2, volume_direct_to_slippage=0.1
    )
    expected = 0.1 + 0.5 * 0.8 * 1.2
    assert math.isclose(true_effect, expected)


def test_synthetic_data_is_reproducible_given_the_same_seed() -> None:
    df1, _ = generate_synthetic_market_data(n_samples=50, seed=42)
    df2, _ = generate_synthetic_market_data(n_samples=50, seed=42)
    assert df1.equals(df2)


# =============================================================================
# estimate_causal_effect -- the real, central validation against known ground truth
# =============================================================================


def test_estimate_recovers_the_true_causal_effect_on_synthetic_data() -> None:
    """The real, load-bearing test: DoWhy's estimate must match the KNOWN structural effect, not just run without crashing."""
    df, true_effect = generate_synthetic_market_data(n_samples=5000, seed=0)

    result = estimate_causal_effect(df, action="do(Buy_100_BTC)", baseline_volume=0.0, run_refutation=False)

    expected = true_effect * 100
    assert math.isclose(result.estimated_slippage_impact, expected, rel_tol=0.05)


def test_estimate_scales_linearly_with_real_quantity() -> None:
    df, _ = generate_synthetic_market_data(n_samples=5000, seed=1)
    small = estimate_causal_effect(df, action="do(Buy_10_BTC)", baseline_volume=0.0, run_refutation=False)
    large = estimate_causal_effect(df, action="do(Buy_100_BTC)", baseline_volume=0.0, run_refutation=False)
    assert math.isclose(large.estimated_slippage_impact, small.estimated_slippage_impact * 10, rel_tol=0.05)


def test_estimate_respects_baseline_volume() -> None:
    """The estimate is a real difference relative to baseline_volume, not an absolute level."""
    df, _ = generate_synthetic_market_data(n_samples=5000, seed=2)
    from_zero = estimate_causal_effect(df, action="do(Buy_50_BTC)", baseline_volume=0.0, run_refutation=False)
    from_ten = estimate_causal_effect(df, action="do(Buy_50_BTC)", baseline_volume=10.0, run_refutation=False)
    assert math.isclose(from_zero.estimated_slippage_impact, from_ten.estimated_slippage_impact, rel_tol=0.05)


def test_refutation_passes_on_a_well_specified_synthetic_model() -> None:
    df, _ = generate_synthetic_market_data(n_samples=5000, seed=3)
    result = estimate_causal_effect(df, action="do(Buy_100_BTC)", run_refutation=True)
    assert result.refutation_passed is True


def test_refutation_is_none_when_not_requested() -> None:
    df, _ = generate_synthetic_market_data(n_samples=1000, seed=4)
    result = estimate_causal_effect(df, action="do(Buy_100_BTC)", run_refutation=False)
    assert result.refutation_passed is None


def test_estimate_rejects_data_missing_required_columns() -> None:
    import pandas as pd

    df = pd.DataFrame({"Volume": [1.0, 2.0], "Price_Slippage": [0.1, 0.2]})
    with pytest.raises(ValueError, match="missing required columns"):
        estimate_causal_effect(df, action="do(Buy_100_BTC)")


# =============================================================================
# load_real_market_features -- real historical data, no NaN leakage
# =============================================================================


def test_load_real_market_features_against_real_historical_data() -> None:
    df = load_real_market_features("BTCUSDT", limit_rows=5000)

    assert set(df.columns) == {"Volume", "Spread", "Adverse_Selection", "Price_Slippage"}
    assert len(df) > 1000


def test_load_real_market_features_never_returns_nan() -> None:
    """Real regression test: the rolling-std proxy's first row is mathematically NaN (1-sample std is undefined) -- must be dropped, not passed through."""
    df = load_real_market_features("BTCUSDT", limit_rows=2000)
    assert not df.isna().any().any()


def test_estimate_causal_effect_on_real_data_produces_a_finite_number() -> None:
    df = load_real_market_features("BTCUSDT", limit_rows=5000)
    result = estimate_causal_effect(df, action="do(Buy_1_BTC)", baseline_volume=float(df["Volume"].mean()), run_refutation=False)
    assert math.isfinite(result.estimated_slippage_impact)


def test_load_real_market_features_raises_on_unknown_symbol() -> None:
    with pytest.raises(FileNotFoundError):
        load_real_market_features("DOGEUSDT")
