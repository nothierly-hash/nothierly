class EmergencyAction(BaseModel):
    """One deterministically-detected (never LLM-decided) dangerous chat command.

    See :func:`_classify_emergency_intent` for how this gets produced,
    and the section docstring above for why *executing* it is always the
    caller's job, never this module's.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    action_type: Literal["KILL_SWITCH", "CLOSE_POSITION"]
    instrument: str | None = Field(default=None, description="Set only when action_type == CLOSE_POSITION.")


class ChatReply(BaseModel):
    """One turn of :func:`chat_with_nothierly`'s reply.

    Attributes:
        text: What to show the user -- either the LLM's (or fallback's)
            conversational reply, or one of the deterministic, code-
            authored safety strings (a confirmation request, an
            execution acknowledgement, or a cancellation notice). Never
            LLM-generated when :attr:`pending_action`/
            :attr:`confirmed_action` is set -- see the section docstring.
        source: Where ``text`` came from.
        pending_action: Set when this turn just *detected* a candidate
            emergency command and is asking the user to confirm it. The
            caller must store this (e.g. in ``st.session_state``) and
            pass it back as ``pending_action`` on the *next* call to
            this function -- otherwise the confirmation is meaningless.
        confirmed_action: Set when the user just confirmed a
            previously-pending action. The caller must execute it now
            (flip the Kill Switch / publish the manual close request)
            -- this module never does.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    text: str = Field(min_length=1)
    source: Literal["llm", "fallback", "deterministic"]
    pending_action: EmergencyAction | None = None
    confirmed_action: EmergencyAction | None = None


