_FALLBACK_CONTEXT_PREVIEW_CHARS: Final[int] = 300


def _fallback_verdict(trigger: TriggerType, summary: str, context: str) -> str:
    """Deterministic, template-based stand-in for the LLM -- see the module docstring on why this exists.

    Not a real risk model: a fixed template per trigger, with ``summary``
    interpolated in, plus a truncated echo of ``context`` -- so the
    trader can see what state this canned verdict was (not) actually
    reasoning over, rather than mistaking it for a live opinion on their
    specific positions. Honest about its own nature (says so in its own
    first line) rather than pretending to be a live AI opinion.
    """
    body = _FALLBACK_TEMPLATES[trigger].format(summary=summary)
    context_preview = context.strip().replace("\n", " ")[:_FALLBACK_CONTEXT_PREVIEW_CHARS]
    if context_preview:
        body += f"\n\n(Contexte fourni, non analysé par un LLM : {context_preview}...)"
    return body


