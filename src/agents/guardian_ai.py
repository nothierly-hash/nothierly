"""Nothierly's Chief Risk Officer: an LLM-backed second opinion on dangerous actions.

:func:`assess_risk` (and its synchronous twin, :func:`assess_risk_sync`) is
the entire public surface of this module. Deliberately **not** wired to
Redis or ZeroMQ at all: give it a trigger, a one-line summary, and a block
of context text, and it returns a :class:`GuardianAlert` -- nothing more.
That narrow contract is what lets the exact same function be called from
two very different places without any bus/client coupling to reconcile:

- :class:`~src.agents.execution.agent.ExecutionAgent` (an ``asyncio``
  agent, already inside an event loop) calls :func:`assess_risk`
  directly, then persists the result to Redis itself via its own
  already-connected async client -- see that class's ``_trigger_
  guardian_alert`` for triggers 3 (drawdown) and 4 (signal collision).
- ``src/dashboard/app.py`` (a synchronous, event-loop-free Streamlit
  process -- see that module's docstring on why) calls
  :func:`assess_risk_sync` instead, then persists the result via its own
  already-open synchronous ``redis`` client -- for triggers 1 (risk
  increase) and 2 (manual override against consensus).

Every caller pushes the resulting :class:`GuardianAlert` onto the same
Redis list, ``NOTHIERLY_GUARDIAN_ALERTS`` (the key itself lives with each
caller, not here, for the same "no Redis coupling in this module" reason)
-- so the dashboard's alert banner never needs to know which of the four
triggers produced a given entry, or whether it came from the sync or
async caller.

**LLM provider**: configured via :class:`~core.config.GuardianSettings`
(``GUARDIAN_LLM_PROVIDER``/``GUARDIAN_API_KEY``/``GUARDIAN_MODEL``).
Supports OpenAI's Chat Completions API and Anthropic's Messages API, both
called directly over HTTP via :class:`~core.http_client.
ResilientHttpClient` (no ``openai``/``anthropic`` SDK dependency --
consistent with this project's macro/news agents, which call their own
providers' REST APIs directly rather than pulling in a client SDK for a
handful of endpoints). When unconfigured (``llm_provider="none"``, the
default) or when the live call fails for any reason, falls back to a
deterministic, template-based assessment -- **the safety check itself
must never silently no-op just because a network call failed**; a
dangerous action still gets *a* verdict, even a canned one, never silence.
"""

