class GuardianAlert(BaseModel):
    """One Chief-Risk-Officer verdict, ready to serialize onto ``NOTHIERLY_GUARDIAN_ALERTS``.

    Attributes:
        timestamp: ``time.time()`` when the verdict was produced.
        trigger: Which of the four triggers this responds to.
        summary: One-line, human-written description of the dangerous
            action/condition (not generated by the LLM) -- what the
            dashboard's alert banner leads with.
        verdict: The full three-part assessment: cold risk evaluation,
            mathematical-consequence warning, safer alternative. Either
            LLM-generated prose or the template fallback -- see
            :attr:`source`.
        source: ``"llm"`` if a configured provider actually answered;
            ``"fallback"`` if no provider is configured, or the live
            call failed and this is the deterministic template instead.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    timestamp: float = Field(gt=0)
    trigger: TriggerType
    summary: str = Field(min_length=1)
    verdict: str = Field(min_length=1)
    source: Literal["llm", "fallback"]


async def assess_risk(
    *,
    trigger: TriggerType,
    summary: str,
    context: str,
    settings: AppSettings | None = None,
) -> GuardianAlert:
    """Ask the Chief Risk Officer to weigh in on one dangerous action or condition.

    Args:
        trigger: Which of the four triggers fired.
        summary: One-line description of what's dangerous (e.g. "Risk
            slider raised to 4.5%"). Never sent through the LLM as-is in
            isolation -- folded into ``context`` for the actual prompt,
            but kept separately here since it's also what the dashboard
            shows as the alert's headline, independent of whatever the
            model (or the fallback template) says.
        context: Market/position context plus the specific dangerous
            action, formatted as free text -- this is the user-turn
            content sent to the LLM (or interpolated into the fallback
            template). Building this text is deliberately the caller's
            job: :class:`~src.agents.execution.agent.ExecutionAgent` and
            the dashboard have access to differently-shaped state (one
            has live ``PositionState`` objects, the other has already-
            serialized Redis JSON), and neither shape belongs in this
            module.
        settings: Defaults to ``get_settings()``.

    Returns:
        A :class:`GuardianAlert`. Never raises for an LLM-side failure
        (network error, malformed response, missing API key) -- falls
        back to the deterministic template instead, so a dangerous
        action always gets *some* verdict.
    """
    settings = settings or get_settings()
    guardian_settings = settings.guardian

    if guardian_settings.llm_provider == "none" or guardian_settings.api_key is None:
        verdict, source = _fallback_verdict(trigger, summary, context), "fallback"
    else:
        try:
            verdict = await _call_llm(guardian_settings, _SYSTEM_PROMPT, [{"role": "user", "content": context}])
            source = "llm"
        except Exception:
            _log.exception(
                "guardian_ai_llm_call_failed_using_fallback",
                trigger=trigger,
                provider=guardian_settings.llm_provider,
            )
            verdict, source = _fallback_verdict(trigger, summary, context), "fallback"

    return GuardianAlert(
        timestamp=time.time(), trigger=trigger, summary=summary, verdict=verdict, source=source  # type: ignore[arg-type]
    )


def assess_risk_sync(
    *,
    trigger: TriggerType,
    summary: str,
    context: str,
    settings: AppSettings | None = None,
) -> GuardianAlert:
    """Synchronous wrapper around :func:`assess_risk`, for Streamlit's event-loop-free process.

    ``src/dashboard/app.py`` runs as a plain synchronous script (see that
    module's docstring on why it can never share an event loop with the
    ``asyncio`` agents) -- this is the one place in this module that
    exists purely to bridge that gap, via a fresh, short-lived
    ``asyncio.run()`` for this single call. Safe to call from Streamlit
    specifically because Streamlit's own request handling is
    thread-per-script-run, not itself inside a running event loop --
    calling this from code that already has one running would raise
    (``asyncio.run()`` cannot be nested).
    """
    return asyncio.run(assess_risk(trigger=trigger, summary=summary, context=context, settings=settings))


async def _call_llm(guardian_settings: GuardianSettings, system_prompt: str, messages: list[dict[str, str]]) -> str:
    """Dispatch to the configured provider's REST API. Raises on any failure -- see :func:`assess_risk`.

    Args:
        guardian_settings: Provider/credentials.
        system_prompt: Which persona to use -- the CRO prompt
            (:data:`_SYSTEM_PROMPT`, single-turn) or the chat persona
            (:data:`_CHAT_SYSTEM_PROMPT`, multi-turn) -- shared plumbing,
            different callers.
        messages: ``[{"role": "user"|"assistant", "content": ...}, ...]``,
            oldest first. A single-element list for :func:`assess_risk`;
            the running conversation (plus the latest turn) for
            :func:`chat_with_nothierly`.
    """
    if guardian_settings.api_key is None:
        raise ValueError("GUARDIAN_API_KEY is not set.")
    api_key = guardian_settings.api_key.get_secret_value()
    model = guardian_settings.model or _DEFAULT_MODEL_BY_PROVIDER[guardian_settings.llm_provider]

    async with ResilientHttpClient(timeout_seconds=_LLM_TIMEOUT_SECONDS) as http:
        if guardian_settings.llm_provider == "openai":
            return await _call_openai(http, api_key, model, system_prompt, messages)
        return await _call_anthropic(http, api_key, model, system_prompt, messages)


async def _call_openai(
    http: ResilientHttpClient, api_key: str, model: str, system_prompt: str, messages: list[dict[str, str]]
) -> str:
    """Call OpenAI's Chat Completions API directly (no ``openai`` SDK dependency -- see the module docstring)."""
    body = await http.post_json(
        "https://api.openai.com/v1/chat/completions",
        json_body={
            "model": model,
            "messages": [{"role": "system", "content": system_prompt}, *messages],
            "max_tokens": _LLM_MAX_TOKENS,
            "temperature": 0.2,
        },
        headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
    )
    return str(body["choices"][0]["message"]["content"]).strip()


async def _call_anthropic(
    http: ResilientHttpClient, api_key: str, model: str, system_prompt: str, messages: list[dict[str, str]]
) -> str:
    """Call Anthropic's Messages API directly (no ``anthropic`` SDK dependency -- see the module docstring).

    Anthropic's Messages API takes the system prompt as its own top-level
    ``system`` field, never as a ``"system"``-role entry inside
    ``messages`` (unlike OpenAI) -- ``messages`` here is exactly the
    conversation turns, nothing else.
    """
    body = await http.post_json(
        "https://api.anthropic.com/v1/messages",
        json_body={
            "model": model,
            "max_tokens": _LLM_MAX_TOKENS,
            "system": system_prompt,
            "messages": messages,
        },
        headers={
            "x-api-key": api_key,
            "anthropic-version": "2023-06-01",
            "content-type": "application/json",
        },
    )
    return str(body["content"][0]["text"]).strip()


