def _classify_emergency_intent(text: str) -> EmergencyAction | None:
    """Deterministically decide whether ``text`` is an emergency command -- never LLM-decided.

    Two independent guards keep an ordinary theoretical question (e.g.
    "que se passerait-il si je fermais ma position sur BTC ?" -- which
    contains "ferme" but means nothing of the sort) from ever being
    mistaken for a real order:

    1. **Any question marker anywhere in the message disqualifies it
       outright** (see :data:`_QUESTION_MARKERS`), checked first, before
       any keyword match is even attempted.
    2. **A keyword match alone is still never sufficient on its own to
       execute anything** -- this function only ever returns a
       *candidate* action; :func:`chat_with_nothierly` always turns that
       into a confirmation request first (:attr:`ChatReply.pending_action`)
       and only executes after an explicit affirmative reply on a
       *separate*, later turn (see :func:`_is_affirmative_confirmation`).
       A false positive here costs one extra "did you mean...?" exchange,
       never a real action.

    Returns:
        A :class:`EmergencyAction` candidate, or ``None`` if ``text``
        doesn't look like a command at all.
    """
    lowered = f" {text.lower().strip()} "

    if any(marker in lowered for marker in _QUESTION_MARKERS):
        return None

    if any(phrase in lowered for phrase in _KILL_SWITCH_PHRASES) or re.search(r"\bkill\b", lowered):
        return EmergencyAction(action_type="KILL_SWITCH")

    if any(keyword in lowered for keyword in _CLOSE_KEYWORDS):
        for alias, instrument in _INSTRUMENT_ALIASES.items():
            if alias in lowered:
                return EmergencyAction(action_type="CLOSE_POSITION", instrument=instrument)
        # "ferme"/"close" with no instrument named -- the safer,
        # fully-covering catch-all rather than guessing which position.
        return EmergencyAction(action_type="KILL_SWITCH")

    return None


def _is_affirmative_confirmation(text: str) -> bool:
    """Whether ``text`` is an unambiguous "yes, do it" -- deliberately strict.

    Requires the message to *be* (not merely contain) one of
    :data:`_AFFIRMATIVE_CONFIRMATIONS`, optionally followed by more words
    (e.g. "oui, vas-y") -- a bare mention of "oui" deep inside an
    unrelated sentence does not count.
    """
    lowered = text.lower().strip()
    return any(lowered == word or lowered.startswith(f"{word} ") or lowered.startswith(f"{word},") for word in _AFFIRMATIVE_CONFIRMATIONS)


def _describe_action(action: EmergencyAction) -> str:
    if action.action_type == "KILL_SWITCH":
        return "Kill Switch global (arrêt de toute opération financière)."
    return f"Fermeture de la position {action.instrument}."


def _build_confirmation_prompt(action: EmergencyAction) -> str:
    return (
        f"⚠️ Commande détectée : {_describe_action(action)}\n\n"
        "Confirme explicitement (\"oui\" / \"confirme\") pour exécuter, ou reformule ta "
        "demande pour annuler."
    )


async def chat_with_nothierly(
    *,
    user_message: str,
    conversation_history: list[dict[str, str]],
    context: str,
    pending_action: EmergencyAction | None = None,
    settings: AppSettings | None = None,
) -> ChatReply:
    """One turn of conversation with the Nothierly copilot persona.

    Args:
        user_message: The human's latest message, verbatim.
        conversation_history: Prior turns, oldest first, as
            ``[{"role": "user"|"assistant", "content": ...}, ...]`` --
            not including ``user_message`` itself (appended internally).
        context: Freshly-built, timestamped state text (positions, Kill
            Switch status, latest Guardian alerts, ...) -- the caller's
            job to build (see :mod:`~src.dashboard.app`'s
            ``_build_dashboard_context``), matching every other function
            in this module's "no Redis coupling here" contract. Injected
            as part of the user turn so the persona's "cite your source"
            instruction has real, current data to cite.
        pending_action: The action (if any) this exact conversation was
            asked to confirm on the *previous* turn -- pass back
            whatever :attr:`ChatReply.pending_action` returned then. When
            set, this turn is interpreted *only* as a confirm/cancel for
            that action, never as a fresh message.
        settings: Defaults to ``get_settings()``.

    Returns:
        A :class:`ChatReply`. See that class and the section docstring
        above for why execution is always the caller's responsibility.
    """
    settings = settings or get_settings()

    if pending_action is not None:
        if _is_affirmative_confirmation(user_message):
            return ChatReply(
                text=f"⚠️ ORDRE REÇU. Exécution immédiate. {_describe_action(pending_action)}",
                source="deterministic",
                confirmed_action=pending_action,
            )
        return ChatReply(
            text="Annulé — action non confirmée. Reformule ta demande si tu veux autre chose.",
            source="deterministic",
        )

    detected_action = _classify_emergency_intent(user_message)
    if detected_action is not None:
        return ChatReply(
            text=_build_confirmation_prompt(detected_action), source="deterministic", pending_action=detected_action
        )

    guardian_settings = settings.guardian
    injected_user_turn = f"[CONTEXTE SYSTÈME ACTUEL]\n{context}\n\n[MESSAGE UTILISATEUR]\n{user_message}"
    messages = [*conversation_history, {"role": "user", "content": injected_user_turn}]

    if guardian_settings.llm_provider == "none" or guardian_settings.api_key is None:
        reply_text = _chat_fallback_reply(user_message)
        source: Literal["llm", "fallback"] = "fallback"
    else:
        try:
            reply_text = await _call_llm(guardian_settings, _CHAT_SYSTEM_PROMPT, messages)
            source = "llm"
        except Exception:
            _log.exception("guardian_ai_chat_llm_call_failed_using_fallback", provider=guardian_settings.llm_provider)
            reply_text = _chat_fallback_reply(user_message)
            source = "fallback"

    return ChatReply(text=reply_text, source=source)


def chat_with_nothierly_sync(
    *,
    user_message: str,
    conversation_history: list[dict[str, str]],
    context: str,
    pending_action: EmergencyAction | None = None,
    settings: AppSettings | None = None,
) -> ChatReply:
    """Synchronous wrapper around :func:`chat_with_nothierly` -- see :func:`assess_risk_sync`."""
    return asyncio.run(
        chat_with_nothierly(
            user_message=user_message,
            conversation_history=conversation_history,
            context=context,
            pending_action=pending_action,
            settings=settings,
        )
    )


def _chat_fallback_reply(user_message: str) -> str:
    """Deterministic stand-in reply when no LLM is configured -- honest, not a canned opinion.

    Unlike :func:`_fallback_verdict` (which still produces a real,
    templated 3-part risk assessment for the CRO's four fixed triggers),
    open-ended conversation has no fixed template that could honestly
    stand in for a real answer -- so this says so plainly, per the
    persona's own "no hallucination" rule, rather than pretending to
    analyze a message with no model behind it.
    """
    return (
        "⚠️ Aucun LLM configuré (GUARDIAN_LLM_PROVIDER=none) — je ne peux pas analyser ta "
        f"demande (\"{user_message[:100]}\") sans modèle de langage actif. Configure "
        "GUARDIAN_LLM_PROVIDER/GUARDIAN_API_KEY pour activer la conversation. Les commandes "
        "d'urgence (Kill Switch, fermeture de position) restent fonctionnelles indépendamment "
        "de cette limitation -- elles ne dépendent d'aucun LLM."
    )
